const { test } = require('node:test');
const assert = require('node:assert/strict');
const { spawn } = require('node:child_process');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');

test('accounts isolate trees and persist across restart', async () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'pb-auth-'));
  fs.writeFileSync(path.join(dir, 'state.json'), JSON.stringify({ nodes: [{ id: 'legacy', title: 'Bestaand', length: 10 }] }));
  let child;
  const start = async () => {
    child = spawn(process.execPath, ['server.js'], { cwd: __dirname, env: { ...process.env, PORT: '31987', DATA_DIR: dir }, stdio: ['ignore', 'pipe', 'pipe'] });
    await new Promise((resolve, reject) => {
      child.stdout.once('data', resolve);
      child.once('error', reject);
      child.once('exit', code => reject(new Error(`Server exited: ${code}`)));
    });
  };
  const stop = () => new Promise(resolve => { child.once('exit', resolve); child.kill(); });
  const request = async (route, cookie, method = 'GET', body) => {
    const response = await fetch(`http://localhost:31987/api/${route}`, { method, headers: { ...(cookie ? { Cookie: cookie } : {}), ...(body ? { 'Content-Type': 'application/json' } : {}) }, body: body ? JSON.stringify(body) : undefined });
    return { status: response.status, cookie: response.headers.get('set-cookie')?.split(';')[0], body: await response.json() };
  };
  try {
    await start();
    assert.equal((JSON.parse(fs.readFileSync(path.join(dir, 'state.json'), 'utf8')).users || []).length, 0);
    assert.equal((await request('tree')).status, 401);
    const a = await request('auth/register', null, 'POST', { username: 'alice', password: 'long-test-password' });
    assert.equal(a.status, 200);
    assert.equal(a.body.user.isAdmin, false);
    assert.equal((await request('admin/users', a.cookie)).status, 403);
    assert.equal((await request('admin/backup', a.cookie)).status, 403);
    assert.equal((await request('admin/users')).status, 401);
    assert.equal((await request('tree', a.cookie)).body.roots[0].id, 'legacy');
    assert.ok(fs.existsSync(path.join(dir, 'before-accounts.json')));
    const b = await request('auth/register', null, 'POST', { username: 'bob', password: 'other-test-password' });
    assert.equal((await request('tree', b.cookie)).body.roots.length, 0);
    const group = await request('groups', a.cookie, 'POST', { title: 'School' });
    assert.equal(group.status, 201);
    assert.equal((await request('nodes/legacy', a.cookie, 'PATCH', { groupId: group.body.id, stoppedPage: 7 })).status, 200);
    assert.equal((await request('tree', b.cookie)).body.groups.length, 0);
    assert.equal((await request('nodes', b.cookie, 'POST', { title: 'Other', groupId: group.body.id })).status, 400);
    assert.equal((await request('nodes/legacy', a.cookie, 'PATCH', { stoppedPage: -1 })).status, 400);
    assert.equal((await request('tree', a.cookie)).body.roots[0].progress, 70);
    assert.equal((await request('tree', a.cookie)).body.roots[0].unit, 'paginas');
    const project = await request('nodes', a.cookie, 'POST', { title: 'Werkproject', unit: 'uur', length: 2.5 });
    assert.equal(project.status, 201);
    const childNode = await request('nodes', a.cookie, 'POST', { title: 'Analyse', length: 1.25, parentId: project.body.id });
    assert.equal(childNode.status, 201);
    await request(`nodes/${childNode.body.id}`, a.cookie, 'PATCH', { stoppedPage: 0.5 });
    const partialTree = (await request('tree', a.cookie)).body.roots.find(n => n.id === project.body.id);
    assert.equal(partialTree.children[0].progress, 40);
    assert.equal(partialTree.progress, 20);
    assert.equal((await request(`nodes/${childNode.body.id}/toggle`, a.cookie, 'POST', {})).status, 200);
    const workTree = (await request('tree', a.cookie)).body.roots.find(n => n.id === project.body.id);
    assert.equal(workTree.progress, 50);
    assert.equal(workTree.children[0].unit, 'uur');
    assert.equal(workTree.children[0].completedLength, 1.25);
    assert.equal((await request(`nodes/${project.body.id}`, a.cookie, 'PATCH', { unit: 'Tpoints', stoppedPage: 0.5, groupId: group.body.id })).status, 200);
    assert.equal((await request('tree', a.cookie)).body.roots.find(n => n.id === project.body.id).progress, 50);
    await request(`nodes/${project.body.id}/toggle`, a.cookie, 'POST', { completed: true });
    assert.equal((await request('tree', a.cookie)).body.roots.find(n => n.id === project.body.id).progress, 100);
    await request(`nodes/${project.body.id}/toggle`, a.cookie, 'POST', { completed: false });
    assert.equal((await request('tree', a.cookie)).body.roots.find(n => n.id === project.body.id).progress, 20);
    await request(`nodes/${childNode.body.id}`, a.cookie, 'PATCH', { stoppedPage: 100 });
    assert.equal((await request('tree', a.cookie)).body.roots.find(n => n.id === project.body.id).children[0].progress, 100);
    await request(`nodes/${childNode.body.id}`, a.cookie, 'PATCH', { stoppedPage: null });
    assert.equal((await request('tree', a.cookie)).body.roots.find(n => n.id === project.body.id).children[0].progress, 0);
    assert.equal((await request(`nodes/${childNode.body.id}`, a.cookie, 'PATCH', { unit: 'uur' })).status, 400);
    assert.equal((await request(`nodes/${project.body.id}`, a.cookie, 'PATCH', { unit: '' })).status, 400);
    assert.equal((await request(`nodes/${project.body.id}`, b.cookie, 'PATCH', { unit: 'uur' })).status, 404);
    const backup = (await request('export', a.cookie)).body;
    assert.equal(backup.groups[0].title, 'School');
    assert.equal(backup.nodes[0].stoppedPage, 7);
    assert.equal(backup.nodes.find(n => n.id === project.body.id).unit, 'Tpoints');
    assert.equal((await request('import', a.cookie, 'POST', backup)).status, 200);
    assert.equal((await request('nodes/legacy', b.cookie, 'PATCH', { title: 'Stolen' })).status, 404);
    assert.equal((await request('nodes', b.cookie, 'POST', { title: 'Child', parentId: 'legacy' })).status, 404);
    assert.equal((await request('export', b.cookie)).body.nodes.length, 0);
    assert.equal((await request('import', b.cookie, 'POST', { nodes: [] })).status, 200);
    assert.equal((await request('tree', a.cookie)).body.roots.length, 2);
    assert.equal((await request('import', b.cookie, 'POST', { nodes: [{ id: 'loop', parentId: 'loop' }] })).status, 400);
    assert.equal((await request('auth/login', null, 'POST', { username: 'alice', password: 'wrong-password' })).status, 401);
    await stop();
    await start();
    assert.equal((await request('tree', a.cookie)).body.roots[0].title, 'Bestaand');
    assert.equal((await request('tree', a.cookie)).body.roots[0].stoppedPage, 7);
    assert.equal((await request('tree', a.cookie)).body.groups[0].title, 'School');
    const restored = (await request('tree', a.cookie)).body.roots.find(n => n.id === project.body.id);
    assert.equal(restored.unit, 'Tpoints');
    assert.equal(restored.children[0].unit, 'Tpoints');
    assert.equal(restored.stoppedPage, 0.5);
    assert.equal(restored.totalLength, 2.5);
    assert.equal((await request(`groups/${group.body.id}`, a.cookie, 'DELETE', {})).status, 200);
    assert.equal((await request('tree', a.cookie)).body.roots[0].groupId, null);
    assert.equal((await request('auth/login', null, 'POST', { username: 'alice', password: 'long-test-password' })).status, 200);
    await request('auth/logout', a.cookie, 'POST', {});
    assert.equal((await request('tree', a.cookie)).status, 401);
    const stored = fs.readFileSync(path.join(dir, 'state.json'), 'utf8');
    assert.ok(!stored.includes('long-test-password'));
    const admin = await request('auth/register', null, 'POST', { username: 'Thomas', password: 'admin-test-password' });
    assert.equal(admin.body.user.isAdmin, true);
    assert.equal(admin.body.user.username, 'thomas');
    assert.equal((await request('auth/me', admin.cookie)).body.user.isAdmin, true);
    await request('nodes', b.cookie, 'POST', { title: 'Bob project', length: 10 });
    const accounts = await request('admin/users', admin.cookie);
    const adminBackup = await request('admin/backup', admin.cookie);
    assert.equal(adminBackup.status, 200);
    assert.deepEqual(Object.keys(adminBackup.body.accounts[0]).sort(), ['groups', 'nodes', 'username']);
    assert.equal(adminBackup.body.accounts.find(user => user.username === 'bob').nodes[0].title, 'Bob project');
    const bobId = b.body.user.id;
    const original = (await request(`admin/users/${bobId}/tree`, admin.cookie)).body.roots[0];
    assert.equal((await request(`admin/users/${bobId}/tree`, b.cookie)).status, 403);
    assert.equal((await request('admin/backup', b.cookie, 'POST', { mode: 'replace', backup: adminBackup.body })).status, 403);
    await request(`nodes/${original.id}`, b.cookie, 'DELETE', {});
    const newer = (await request('nodes', b.cookie, 'POST', { title: 'Na de back-up' })).body;
    const merged = await request('admin/backup', admin.cookie, 'POST', { mode: 'merge', backup: adminBackup.body });
    assert.equal(merged.body.projectCount, 1);
    const mergedIds = (await request('tree', b.cookie)).body.roots.map(root => root.id);
    assert.deepEqual(new Set(mergedIds), new Set([original.id, newer.id]));
    assert.equal((await request('admin/backup', admin.cookie, 'POST', { mode: 'merge', backup: adminBackup.body })).body.projectCount, 0);
    assert.equal((await request('admin/backup', admin.cookie, 'POST', { mode: 'replace', backup: adminBackup.body })).status, 200);
    assert.deepEqual((await request('tree', b.cookie)).body.roots.map(root => root.id), [original.id]);
    assert.equal(accounts.status, 200);
    assert.equal(accounts.body.users.length, 3);
    assert.equal(accounts.body.users.find(u => u.id === b.body.user.id).projectCount, 1);
    assert.deepEqual(Object.keys(accounts.body.users[0]).sort(), ['id', 'isAdmin', 'projectCount', 'username']);
    assert.equal((await request(`admin/users/${admin.body.user.id}`, admin.cookie, 'DELETE', {})).status, 400);
    assert.equal((await request(`admin/users/${a.body.user.id}`, b.cookie, 'DELETE', {})).status, 403);
    assert.equal((await request(`admin/users/${a.body.user.id}/password`, b.cookie, 'POST', { password: 'not-permitted-password' })).status, 403);
    assert.equal((await request(`admin/users/${b.body.user.id}/password`, admin.cookie, 'POST', { password: 'short' })).status, 400);
    const reset = await request(`admin/users/${b.body.user.id}/password`, admin.cookie, 'POST', { password: 'reset-test-password' });
    assert.equal(reset.status, 200);
    assert.equal(reset.body.signedOut, false);
    assert.equal((await request('tree', b.cookie)).status, 401);
    assert.equal((await request('auth/login', null, 'POST', { username: 'bob', password: 'other-test-password' })).status, 401);
    const newBob = await request('auth/login', null, 'POST', { username: 'bob', password: 'reset-test-password' });
    assert.equal(newBob.status, 200);
    assert.equal((await request('tree', newBob.cookie)).body.roots[0].title, 'Bob project');
    await stop();
    await start();
    assert.equal((await request('auth/me', admin.cookie)).body.user.isAdmin, true);
    assert.equal((await request(`admin/users/${b.body.user.id}`, admin.cookie, 'DELETE', {})).status, 200);
    assert.equal((await request('tree', newBob.cookie)).status, 401);
    assert.equal((await request('auth/login', null, 'POST', { username: 'bob', password: 'reset-test-password' })).status, 401);
    const remaining = JSON.parse(fs.readFileSync(path.join(dir, 'state.json'), 'utf8'));
    assert.equal(remaining.users.some(u => u.id === b.body.user.id), false);
    assert.equal(remaining.sessions.some(s => s.userId === b.body.user.id), false);
    assert.ok(!JSON.stringify(remaining).includes('reset-test-password'));
    const ownReset = await request(`admin/users/${admin.body.user.id}/password`, admin.cookie, 'POST', { password: 'new-admin-password' });
    assert.equal(ownReset.body.signedOut, true);
    assert.equal((await request('admin/users', admin.cookie)).status, 401);
    assert.equal((await request('auth/login', null, 'POST', { username: 'THOMAS', password: 'new-admin-password' })).body.user.isAdmin, true);
  } finally {
    if (child && child.exitCode === null) await stop();
    fs.rmSync(dir, { recursive: true, force: true });
  }
});
