const { test } = require('node:test');
const assert = require('node:assert/strict');
const { spawn } = require('node:child_process');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const vm = require('node:vm');

test('scoped sharing adds independent copies and validates AI JSON', async () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'progresset-sharing-'));
  let child;
  const start = async () => {
    child = spawn(process.execPath, ['server.js'], { cwd: __dirname, env: { ...process.env, PORT: '31989', DATA_DIR: dir }, stdio: ['ignore', 'pipe', 'pipe'] });
    await new Promise((resolve, reject) => { child.stdout.once('data', resolve); child.once('error', reject); child.once('exit', code => reject(new Error(`Server exited: ${code}`))); });
  };
  const stop = () => new Promise(resolve => { child.once('exit', resolve); child.kill(); });
  const request = async (route, cookie, method = 'GET', body) => {
    const response = await fetch(`http://localhost:31989/api/${route}`, { method, headers: { ...(cookie ? { Cookie: cookie } : {}), ...(body ? { 'Content-Type': 'application/json' } : {}) }, body: body ? JSON.stringify(body) : undefined });
    return { status: response.status, cookie: response.headers.get('set-cookie')?.split(';')[0], body: await response.json() };
  };
  try {
    await start();
    const a = (await request('auth/register', null, 'POST', { username: 'alice', password: 'alice-password-123' })).cookie;
    const b = (await request('auth/register', null, 'POST', { username: 'bob', password: 'bob-password-123' })).cookie;
    const group = (await request('groups', a, 'POST', { title: 'School' })).body;
    const project = (await request('nodes', a, 'POST', { title: 'Algebra', length: 100, groupId: group.id })).body;
    const intro = (await request('nodes', a, 'POST', { title: 'Intro', length: 25, parentId: project.id })).body;
    await request('nodes', a, 'POST', { title: 'Verwerking', length: 75, parentId: project.id });
    await request('nodes', a, 'POST', { title: 'Fysica', length: 50, groupId: group.id });
    await request('nodes', a, 'POST', { title: 'Prive', length: 10 });
    await request(`nodes/${intro.id}/toggle`, a, 'POST', {});
    await request(`nodes/${project.id}`, a, 'PATCH', { stoppedPage: 30 });
    const existing = (await request('nodes', b, 'POST', { title: 'Bestaand', length: 20 })).body;
    assert.equal((await request(`share/project/${project.id}`)).status, 401);
    assert.equal((await request(`share/project/${project.id}`, b)).status, 404);
    assert.equal((await request(`share/group/${group.id}`, b)).status, 404);
    assert.equal((await request(`share/project/${intro.id}`, a)).status, 404);
    const shared = (await request(`share/project/${project.id}`, a)).body;
    assert.equal(shared.type, 'project');
    assert.equal(shared.roots.length, 1);
    assert.equal(shared.roots[0].children.length, 2);
    assert.equal(shared.roots[0].completed, undefined);
    assert.equal(shared.roots[0].stoppedPage, undefined);
    assert.ok(!JSON.stringify(shared).includes(project.id));
    assert.ok(!JSON.stringify(shared).includes('Prive'));
    const imported = await request('share/import', b, 'POST', { payload: shared });
    assert.equal(imported.status, 201);
    assert.equal(imported.body.importedCount, 3);
    let tree = (await request('tree', b)).body;
    assert.ok(tree.roots.some(root => root.id === existing.id));
    const copy = tree.roots.find(root => root.title === 'Algebra');
    assert.notEqual(copy.id, project.id);
    assert.notEqual(copy.children[0].id, intro.id);
    assert.equal(copy.progress, 0);
    assert.equal(copy.groupId, null);
    const withProgress = (await request(`share/project/${project.id}?progress=1`, a)).body;
    assert.equal(withProgress.roots[0].stoppedPage, 30);
    await request('share/import', b, 'POST', { payload: withProgress, keepProgress: true });
    tree = (await request('tree', b)).body;
    assert.equal(tree.roots.find(root => root.stoppedPage === 30).progress, 30);
    const sharedGroup = (await request(`share/group/${group.id}`, a)).body;
    assert.equal(sharedGroup.roots.length, 2);
    assert.equal(sharedGroup.group.title, 'School');
    const groupImport = await request('share/import', b, 'POST', { payload: sharedGroup });
    assert.equal(groupImport.status, 201);
    await request('share/import', b, 'POST', { payload: sharedGroup });
    tree = (await request('tree', b)).body;
    assert.ok(tree.groups.some(g => g.title === 'School (2)'));
    assert.equal(tree.roots.filter(root => root.groupId === groupImport.body.groupId).length, 2);
    const groupCount = tree.groups.length;
    await request('share/import', b, 'POST', { payload: sharedGroup, targetGroupId: groupImport.body.groupId });
    assert.equal((await request('tree', b)).body.groups.length, groupCount);
    assert.equal((await request('share/import', b, 'POST', { payload: shared, targetGroupId: group.id })).status, 400);
    const before = (await request('export', b)).body;
    const invalid = structuredClone(sharedGroup);
    invalid.roots[1].length = -1;
    assert.equal((await request('share/import', b, 'POST', { payload: invalid })).status, 400);
    const after = (await request('export', b)).body;
    assert.deepEqual(after.nodes, before.nodes);
    assert.deepEqual(after.groups, before.groups);
    assert.equal((await request('share/import', b, 'POST', { payload: { nodes: [] } })).status, 400);
    const prompt = vm.runInNewContext(fs.readFileSync(path.join(__dirname, 'public/ai-prompt.js'), 'utf8') + '\nAI_COURSE_PROMPT;');
    const startIndex = prompt.indexOf('\n{\n');
    const endIndex = prompt.indexOf('\n}\n', startIndex);
    const sample = JSON.parse(prompt.slice(startIndex + 1, endIndex + 2));
    assert.equal((await request('share/import', b, 'POST', { payload: sample })).status, 201);
    const aiCopy = (await request('tree', b)).body.roots.find(root => root.title === 'Discrete algebra examen');
    assert.equal(aiCopy.totalLength, 150);
    assert.equal(aiCopy.children[0].children[1].totalLength, 75);
    assert.ok(prompt.includes('Verzin geen'));
    assert.equal((await request('tree', a)).body.roots.length, 3);
    await stop();
    await start();
    assert.ok((await request('tree', b)).body.roots.some(root => root.id === aiCopy.id));
  } finally {
    if (child && child.exitCode === null) await stop();
    fs.rmSync(dir, { recursive: true, force: true });
  }
});
